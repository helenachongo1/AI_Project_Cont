class Pathfinder:
    def __init__(self, matrix):
        self.matrix = matrix
        self.grid = Grid(matrix=matrix)
        self.start_x, self.start_y = 18, 9
        self.current_position = [self.start_x, self.start_y]  # Use a list for mutability
        self.start_marker = pygame.image.load("C:/Users/Acer/Downloads/output-onlinepngtools.png").convert_alpha()  # Load the marker image

    def draw_active_cell(self):
        mouse_pos = pygame.mouse.get_pos()
        row = mouse_pos[1] // 32
        col = mouse_pos[0] // 32
        current_cell_value = self.matrix[row][col]
        if current_cell_value == 1:
            rect = pygame.Rect((col * 32, row * 32), (32, 32))
            pygame.draw.rect(screen, (255, 0, 0, 128), rect)

    def draw_start_marker(self):
        # Draw the start marker at the current position
        screen.blit(self.start_marker, (self.current_position[0] * 32, self.current_position[1] * 32))

    def move(self, dx, dy):
        new_x = self.current_position[0] + dx
        new_y = self.current_position[1] + dy
        # Check bounds and obstacles
        if (0 <= new_x < len(self.matrix[0]) and 0 <= new_y < len(self.matrix) and 
            self.matrix[new_y][new_x] == 1):  # Assuming 1 is a walkable cell
            self.current_position[0] = new_x
            self.current_position[1] = new_y

    def update(self):
        self.draw_active_cell()
        self.draw_start_marker()  # Call the draw method for the start marker

